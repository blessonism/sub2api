type adminUsageRepoCapture struct {
	service.UsageLogRepository
	listParams     pagination.PaginationParams
	listFilters    usagestats.UsageLogFilters
	listCalls      int
	statsFilters   usagestats.UsageLogFilters
	summaryFilters usagestats.UsageLogFilters
}

func (s *adminUsageRepoCapture) ListWithFilters(ctx context.Context, params pagination.PaginationParams, filters usagestats.UsageLogFilters) ([]service.UsageLog, *pagination.PaginationResult, error) {
	s.listCalls++
	s.listParams = params
	s.listFilters = filters
	return []service.UsageLog{}, &pagination.PaginationResult{
		Total:    0,
		Page:     params.Page,
		PageSize: params.PageSize,
		Pages:    0,
	}, nil
}

func (s *adminUsageRepoCapture) GetStatsWithFilters(ctx context.Context, filters usagestats.UsageLogFilters) (*usagestats.UsageStats, error) {
	s.statsFilters = filters
	return &usagestats.UsageStats{}, nil
}

func (s *adminUsageRepoCapture) GetSharedIPUsersSummary(ctx context.Context, filters usagestats.UsageLogFilters) (*usagestats.SharedIPUsersSummary, error) {
	s.summaryFilters = filters
	return &usagestats.SharedIPUsersSummary{
		IPCount:       2,
		UserCount:     5,
		RecordCount:   8,
		IPGroupsLimit: 50,
		IPGroups: []usagestats.SharedIPGroupSummaryItem{
			{
				IPAddress:   "203.0.113.9",
				UserCount:   2,
				RecordCount: 6,
				UsersLimit:  20,
				Users: []usagestats.SharedIPGroupUserSummaryItem{
					{UserID: 7, Email: "risk@example.com", RecordCount: 4},
					{UserID: 8, Email: "peer@example.com", RecordCount: 2},
				},
			},
		},
	}, nil
}

func newAdminUsageRequestTypeTestRouter(repo *adminUsageRepoCapture) *gin.Engine {
	gin.SetMode(gin.TestMode)
	usageSvc := service.NewUsageService(repo, nil, nil, nil)
	handler := NewUsageHandler(usageSvc, nil, nil, nil)
	router := gin.New()
	router.GET("/admin/usage", handler.List)
	router.GET("/admin/usage/stats", handler.Stats)
	return router
}

func TestAdminUsageListRequestTypePriority(t *testing.T) {
	repo := &adminUsageRepoCapture{}
	router := newAdminUsageRequestTypeTestRouter(repo)

	req := httptest.NewRequest(http.MethodGet, "/admin/usage?request_type=ws_v2&stream=false", nil)
	rec := httptest.NewRecorder()
	router.ServeHTTP(rec, req)

	require.Equal(t, http.StatusOK, rec.Code)
	require.NotNil(t, repo.listFilters.RequestType)
	require.Equal(t, int16(service.RequestTypeWSV2), *repo.listFilters.RequestType)
	require.Nil(t, repo.listFilters.Stream)
}

