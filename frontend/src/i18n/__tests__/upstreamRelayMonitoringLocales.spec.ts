import { describe, expect, it } from 'vitest'

import en from '../locales/en'
import zh from '../locales/zh'

describe('upstream relay monitoring locales', () => {
  it('describes backend automatic monitoring without stale manual-only wording', () => {
    const zhDescription = zh.admin.upstreamRelayGroupMonitoring.monitoring.description
    const enDescription = en.admin.upstreamRelayGroupMonitoring.monitoring.description
    const zhStatus = zh.admin.upstreamRelayGroupMonitoring.monitoring.status
    const enStatus = en.admin.upstreamRelayGroupMonitoring.monitoring.status

    expect(zhDescription).toContain('自动应用需要显式开启')
    expect(zhDescription).not.toContain('当前阶段仅保存配置和支持手动触发')
    expect(zhStatus.running).toBe('自动监控运行中')
    expect(zhStatus.disabled).toBe('自动监控未启用')
    expect(zhStatus.detailBoth).toContain('自动同步')
    expect(zhStatus.detailBoth).toContain('自动探测')
    expect(zhStatus.detailRecommendationOnly).toContain('不会修改 priority')
    expect(zh.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.sync).toContain('同步')
    expect(zh.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.probe).toContain('探测')
    expect(zh.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.recommendation).toContain('推荐')
    expect(zh.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.autoApply).toContain('自动应用')
    expect(enDescription).toContain('Auto-apply must be explicitly enabled')
    expect(enDescription).not.toContain('only saves configuration')
    expect(enStatus.running).toBe('Auto Monitoring Running')
    expect(enStatus.disabled).toBe('Auto Monitoring Not Enabled')
    expect(enStatus.detailRecommendationOnly).toContain('priority is not changed')
    expect(en.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.sync).toContain('Sync')
    expect(en.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.probe).toContain('Probe')
    expect(en.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.recommendation).toContain('Recommendation')
    expect(en.admin.upstreamRelayGroupMonitoring.monitoring.statusChips.autoApply).toContain('Auto Apply')
  })

  it('contains recommendation run source audit labels in both locales', () => {
    const zhRecommendations = zh.admin.upstreamRelayGroupMonitoring.recommendations
    const enRecommendations = en.admin.upstreamRelayGroupMonitoring.recommendations

    expect(zhRecommendations.colSource).toBe('来源')
    expect(zhRecommendations.sourceSystem).toBe('系统自动生成')
    expect(zhRecommendations.sourceManual).toBe('管理员手动生成')
    expect(zhRecommendations.failed).toBe('生成失败')
    expect(zhRecommendations.running).toBe('生成中')
    expect(zhRecommendations.unknown).toBe('状态未知')
    expect(zhRecommendations.appliedBySystem).toBe('系统自动应用')
    expect(zhRecommendations.appliedByManual).toBe('管理员手动应用')
    expect(enRecommendations.colSource).toBe('Source')
    expect(enRecommendations.sourceSystem).toBe('Generated by system')
    expect(enRecommendations.sourceManual).toBe('Generated manually')
    expect(enRecommendations.failed).toBe('Failed')
    expect(enRecommendations.running).toBe('Running')
    expect(enRecommendations.unknown).toBe('Unknown')
    expect(enRecommendations.appliedBySystem).toBe('Applied by system')
    expect(enRecommendations.appliedByManual).toBe('Applied manually')
  })

  it('contains usage history tab and table labels in both locales', () => {
    const zhFeature = zh.admin.upstreamRelayGroupMonitoring
    const enFeature = en.admin.upstreamRelayGroupMonitoring

    expect(zhFeature.actionGroups.data).toBe('数据刷新')
    expect(zhFeature.actionGroups.recommendation).toBe('推荐生成')
    expect(enFeature.actionGroups.data).toBe('Data Refresh')
    expect(enFeature.actionGroups.recommendation).toBe('Recommendation')
    expect(zhFeature.tabs.usageHistory).toBe('历史用量')
    expect(enFeature.tabs.usageHistory).toBe('Usage History')
    expect(zhFeature.usageHistory.description).toContain('最终日用量汇总')
    expect(enFeature.usageHistory.description).toContain('final daily usage summaries')
    expect(zhFeature.usageHistory.startDate).toBe('开始日期')
    expect(zhFeature.usageHistory.endDate).toBe('结束日期')
    expect(zhFeature.usageHistory.connector).toBe('连接器')
    expect(zhFeature.usageHistory.groupId).toBe('上游分组 ID')
    expect(zhFeature.usageHistory.keyword).toBe('关键词')
    expect(zhFeature.usageHistory.onlyAnomalies).toBe('仅看异常')
    expect(zhFeature.usageHistory.summaryCost).toContain('当前页')
    expect(zhFeature.usageHistory.summaryTokens).toContain('当前页')
    expect(zhFeature.usageHistory.summaryConnectors).toContain('当前页')
    expect(zhFeature.usageHistory.summaryGroups).toContain('当前页')
    expect(zhFeature.usageHistory.summaryCostPerMillion).toContain('每百万')
    expect(zhFeature.usageHistory.appliedFilterSummary).toContain('当前结果')
    expect(zhFeature.usageHistory.resultUsesAppliedFilters).toContain('未应用条件')
    expect(zhFeature.usageHistory.currentPageScopeHint).toContain('当前页汇总')
    expect(zhFeature.usageHistory.invalidDateRange).toContain('开始日期不能晚于结束日期')
    expect(zhFeature.usageHistory.resetFilters).toBe('重置筛选')
    expect(zhFeature.usageHistory.emptyAnomalies).toBe('当前页暂无异常记录')
    expect(zhFeature.usageHistory.shortcutLast7d).toBe('近 7 天')
    expect(zhFeature.usageHistory.groupSubtotalCost).toContain('成本')
    expect(zhFeature.usageHistory.flagCostWithoutTokens).toBe('有成本无 Token')
    expect(zhFeature.usageHistory.filtersPending).toBe('筛选条件待应用')
    expect(zhFeature.usageHistory.applyFilters).toBe('应用筛选')
    expect(zhFeature.usageHistory.loading).toBe('正在加载历史用量')
    expect(zhFeature.usageHistory.colDate).toBe('日期')
    expect(zhFeature.usageHistory.colGroup).toBe('分组')
    expect(zhFeature.usageHistory.colCost).toBe('Actual Cost')
    expect(zhFeature.usageHistory.colTokens).toBe('Token')
    expect(zhFeature.usageHistory.colCheckedAt).toBe('采集时间')
    expect(enFeature.usageHistory.colDate).toBe('Date')
    expect(enFeature.usageHistory.startDate).toBe('Start Date')
    expect(enFeature.usageHistory.endDate).toBe('End Date')
    expect(enFeature.usageHistory.connector).toBe('Connector')
    expect(enFeature.usageHistory.groupId).toBe('Upstream Group ID')
    expect(enFeature.usageHistory.keyword).toBe('Keyword')
    expect(enFeature.usageHistory.onlyAnomalies).toBe('Anomalies only')
    expect(enFeature.usageHistory.summaryCost).toContain('Current Page')
    expect(enFeature.usageHistory.summaryTokens).toContain('Current Page')
    expect(enFeature.usageHistory.summaryConnectors).toContain('Current Page')
    expect(enFeature.usageHistory.summaryGroups).toContain('Current Page')
    expect(enFeature.usageHistory.summaryCostPerMillion).toContain('1M')
    expect(enFeature.usageHistory.appliedFilterSummary).toContain('Current result')
    expect(enFeature.usageHistory.resultUsesAppliedFilters).toContain('pending changes')
    expect(enFeature.usageHistory.currentPageScopeHint).toContain('Current page summary')
    expect(enFeature.usageHistory.invalidDateRange).toContain('Start date cannot be later than end date')
    expect(enFeature.usageHistory.resetFilters).toBe('Reset Filters')
    expect(enFeature.usageHistory.emptyAnomalies).toBe('No anomalies on the current page')
    expect(enFeature.usageHistory.shortcutLast7d).toBe('Last 7 Days')
    expect(enFeature.usageHistory.groupSubtotalCost).toContain('Cost')
    expect(enFeature.usageHistory.flagCostWithoutTokens).toBe('Cost without tokens')
    expect(enFeature.usageHistory.filtersPending).toBe('Filters pending')
    expect(enFeature.usageHistory.applyFilters).toBe('Apply Filters')
    expect(enFeature.usageHistory.loading).toBe('Loading usage history')
    expect(enFeature.usageHistory.colGroup).toBe('Group')
    expect(enFeature.usageHistory.colCost).toBe('Actual Cost')
    expect(enFeature.usageHistory.colTokens).toBe('Tokens')
    expect(enFeature.usageHistory.colCheckedAt).toBe('Checked At')
    expect(zhFeature.applyDialog.confirmationText).toContain('批量修改账号 priority')
    expect(enFeature.applyDialog.confirmationText).toContain('changes account priority in bulk')
  })
})
